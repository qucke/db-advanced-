        ADD CONSTRAINT fk_users_rank FOREIGN KEY (rank_id) REFERENCES ranks(id);

    ALTER TABLE logs 
        ADD CONSTRAINT fk_logs_user FOREIGN KEY (user_id) REFERENCES users(id),
        ADD CONSTRAINT fk_logs_equipment FOREIGN KEY (equipment_id) REFERENCES equipments(id);

    ALTER TABLE parameters 
        ADD CONSTRAINT fk_param_log FOREIGN KEY (log_id) REFERENCES logs(id),
        ADD CONSTRAINT fk_param_type FOREIGN KEY (parametr_id) REFERENCES types_parameters(id),
        ADD CONSTRAINT fk_param_unit FOREIGN KEY (units_id) REFERENCES units_measurement(id);

    ALTER TABLE temperature_calculations 
        ADD CONSTRAINT fk_temp_calc_log FOREIGN KEY (log_id) REFERENCES logs(id);

    -- 2. Создание ограничений (CHECK)
    
    -- Ограничение возраста пользователя (от 18 до 100 лет)
    ALTER TABLE users 
        ADD CONSTRAINT chk_users_age CHECK (age >= 18 AND age <= 100);

    -- Составное ограничение для таблицы parameters (проверка диапазонов в зависимости от parametr_id).
    ALTER TABLE parameters 
        ADD CONSTRAINT chk_parameter_ranges CHECK (
            parametr_id = 1 OR  -- Высота метеопоста (без жестких ограничений)
            (parametr_id = 2 AND parametr_value BETWEEN -58 AND 58) OR   -- Температура
