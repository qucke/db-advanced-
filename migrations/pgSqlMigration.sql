    DROP TABLE IF EXISTS temperature_calculations CASCADE;
    DROP TABLE IF EXISTS parameters CASCADE;
    DROP TABLE IF EXISTS logs CASCADE;
    DROP TABLE IF EXISTS users CASCADE;
    DROP TABLE IF EXISTS equipments CASCADE;
    DROP TABLE IF EXISTS ranks CASCADE;
    DROP TABLE IF EXISTS types_parameters CASCADE;
    DROP TABLE IF EXISTS units_measurement CASCADE;

    -- 2. Создание таблиц-справочников
    CREATE TABLE ranks (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name varchar(255) UNIQUE NOT NULL
    );

    CREATE TABLE equipments (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name varchar(255) UNIQUE NOT NULL
    );

    CREATE TABLE units_measurement (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name varchar(255) NOT NULL UNIQUE
    );

    CREATE TABLE types_parameters (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name varchar(255) NOT NULL UNIQUE,
        unit_id int NOT NULL
    );

    -- 3. Создание основных таблиц
    CREATE TABLE users (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name varchar(255) NOT NULL,
        rank_id int,
        age int
    );

    CREATE TABLE logs (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id int NOT NULL,
        equipment_id int NOT NULL,
        date timestamp DEFAULT CURRENT_TIMESTAMP
    );

    -- 4. Таблица параметров в нормализованном виде 
    CREATE TABLE parameters (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        log_id int NOT NULL,
        parametr_id int NOT NULL,
        units_id int NOT NULL,
        parametr_value decimal(10,2) NOT NULL
    );

    -- 5. Расчет температуры
    create table calc_temperature_correction
		(
		   temperature numeric(8,2) not null primary key,
		   correction numeric(8,2) not null
		);

END $$;


