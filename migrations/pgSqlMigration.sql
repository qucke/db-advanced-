CREATE TABLE ranks (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) UNIQUE NOT NULL
);

CREATE TABLE equipments (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) UNIQUE NOT NULL
);

CREATE TABLE units_measurement (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE
);

CREATE TABLE types_parameters (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE,
    unit_id int NOT NULL
);

CREATE TABLE users (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    rank_id int,
    age int
);

CREATE TABLE logs (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id int NOT NULL,
    equipment_id int NOT NULL,
    date timestamp DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE parameters (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_id int NOT NULL,
    parametr_id int NOT NULL,
    units_id int NOT NULL,
    parametr_value decimal(10,2) NOT NULL
);

CREATE TABLE temperature_calculations (
    id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_id int NOT NULL,
    base_temperature decimal(10,2) NOT NULL,
    calculated_temperature decimal(10,2) NOT NULL,
    formula_used varchar(100) DEFAULT 'Стандартная поправка',
    calculation_date timestamp DEFAULT CURRENT_TIMESTAMP
);

